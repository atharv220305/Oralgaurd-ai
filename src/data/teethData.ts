export function getToothGeometricProfile(toothOrFdi: ToothDefinition | number | string): ToothGeometricProfile {
  let fdi = 11;
  let isUpper = true;
  let type: ToothDefinition['type'] = 'incisor';

  if (typeof toothOrFdi === 'object' && toothOrFdi !== null) {
    fdi = toothOrFdi.fdiNumber;
    isUpper = toothOrFdi.arch === 'maxillary';
    type = toothOrFdi.type;
  } else {
    const toothDef = getToothDefinition(String(toothOrFdi));
    if (toothDef) {
      fdi = toothDef.fdiNumber;
      isUpper = toothDef.arch === 'maxillary';
      type = toothDef.type;
    } else {
      const parsed = parseInt(String(toothOrFdi), 10);
      fdi = !isNaN(parsed) ? parsed : 11;
      isUpper = fdi < 30;
      const idx = fdi % 10;
      type = idx <= 2 ? 'incisor' : idx === 3 ? 'canine' : idx <= 5 ? 'premolar' : 'molar';
    }
  }

  const index = fdi % 10;

  if (type === 'incisor') {
    if (isUpper) {
      const isCentral = index === 1;
      return {
        crownHeight: isCentral ? 1.05 : 0.92,
        mesiodistalWidth: isCentral ? 0.94 : 0.80,
        labiolingualDepth: isCentral ? 0.66 : 0.60,
        cervicalTaper: isCentral ? 0.70 : 0.72,
        cuspCount: 0,
        morphology: 'incisor',
        cingulumProminence: isCentral ? 0.65 : 0.60,
        fossaDepth: isCentral ? 0.45 : 0.40,
        cervicalOffset: isCentral ? 0.095 : 0.090,
        labialTorque: isCentral ? 0.14 : 0.10,
        mesiodistalTip: isCentral ? 0.02 : 0.04,
      };
    } else {
      const isCentral = index === 1;
      return {
        crownHeight: isCentral ? 0.84 : 0.88,
        mesiodistalWidth: isCentral ? 0.58 : 0.64,
        labiolingualDepth: isCentral ? 0.54 : 0.56,
        cervicalTaper: isCentral ? 0.74 : 0.72,
        cuspCount: 0,
        morphology: 'incisor',
        cingulumProminence: isCentral ? 0.35 : 0.40,
        fossaDepth: isCentral ? 0.25 : 0.30,
        cervicalOffset: isCentral ? 0.085 : 0.088,
        labialTorque: isCentral ? 0.04 : 0.05,
        mesiodistalTip: isCentral ? 0.01 : 0.03,
      };
    }
  }

  if (type === 'canine') {
    return {
      crownHeight: isUpper ? 1.15 : 1.10,
      mesiodistalWidth: isUpper ? 0.88 : 0.82,
      labiolingualDepth: isUpper ? 0.86 : 0.80,
      cervicalTaper: isUpper ? 0.72 : 0.74,
      cuspCount: 1,
      morphology: 'canine',
      cingulumProminence: isUpper ? 0.80 : 0.55,
      fossaDepth: 0.35,
      cervicalOffset: isUpper ? 0.105 : 0.100,
      labialTorque: isUpper ? 0.06 : 0.03,
      mesiodistalTip: isUpper ? 0.06 : 0.05,
    };
  }

  if (type === 'premolar') {
    const isFirst = index === 4;
    return {
      crownHeight: isUpper ? (isFirst ? 0.88 : 0.84) : (isFirst ? 0.86 : 0.82),
      mesiodistalWidth: isUpper ? (isFirst ? 0.82 : 0.80) : (isFirst ? 0.80 : 0.82),
      labiolingualDepth: isUpper ? (isFirst ? 0.92 : 0.90) : (isFirst ? 0.88 : 0.88),
      cervicalTaper: isFirst ? 0.78 : 0.80,
      cuspCount: 2,
      morphology: 'premolar',
      cingulumProminence: 0.30,
      fossaDepth: isUpper ? 0.60 : 0.55,
      cervicalOffset: 0.090,
      labialTorque: isUpper ? -0.02 : 0.04,
      mesiodistalTip: 0.02,
    };
  }

  // Molar (index 6, 7, 8)
  const isFirstMolar = index === 6;
  const isSecondMolar = index === 7;
  return {
    crownHeight: isFirstMolar ? 0.82 : isSecondMolar ? 0.78 : 0.72,
    mesiodistalWidth: isUpper
      ? (isFirstMolar ? 1.14 : isSecondMolar ? 1.05 : 0.95)
      : (isFirstMolar ? 1.20 : isSecondMolar ? 1.12 : 1.02),
    labiolingualDepth: isUpper
      ? (isFirstMolar ? 1.15 : isSecondMolar ? 1.08 : 0.98)
      : (isFirstMolar ? 1.10 : isSecondMolar ? 1.04 : 0.98),
    cervicalTaper: isFirstMolar ? 0.82 : isSecondMolar ? 0.82 : 0.85,
    cuspCount: isUpper ? (isFirstMolar ? 4 : isSecondMolar ? 4 : 3) : (isFirstMolar ? 5 : isSecondMolar ? 4 : 4),
    morphology: 'molar',
    cingulumProminence: isUpper ? 0.45 : 0.35,
    fossaDepth: isFirstMolar ? 0.75 : 0.68,
    cervicalOffset: isFirstMolar ? 0.095 : 0.092,
    labialTorque: isUpper ? (isFirstMolar ? -0.08 : -0.10) : (isFirstMolar ? 0.15 : 0.16),
    mesiodistalTip: isFirstMolar ? 0.02 : 0.01,
  };
}

export const ALL_TEETH: ToothDefinition[] = [...UPPER_TEETH, ...LOWER_TEETH].map((tooth) => {
  tooth.profile = getToothGeometricProfile(tooth);
  return tooth;
});

export const TEETH_BY_ID: Record<string, ToothDefinition> = ALL_TEETH.reduce(
  (acc, tooth) => {
    acc[tooth.id] = tooth;
    acc[tooth.toothNumber] = tooth;
    return acc;
  },
  {} as Record<string, ToothDefinition>
);

export function toothToOralRegion(tooth: ToothDefinition): OralRegion {
  return {
    id: tooth.id,
    name: tooth.fullName,
    hindiName: tooth.hindiName,
    marathiName: tooth.marathiName,
    riskLevel: tooth.riskLevel,
    description: tooth.description,
    clinicalSignificance: tooth.clinicalSignificance,
    commonPathologies: tooth.commonPathologies,
  };
}

export const TEETH_REGIONS: Record<string, OralRegion> = ALL_TEETH.reduce(
  (acc, tooth) => {
    acc[tooth.id] = toothToOralRegion(tooth);
    acc[tooth.toothNumber] = toothToOralRegion(tooth);
    return acc;
  },
  {} as Record<string, OralRegion>
);

export function isToothId(id: string): boolean {
  return Boolean(TEETH_BY_ID[id] || (id.startsWith('tooth_') && TEETH_BY_ID[id.replace('tooth_', '')]));
}

export function getToothDefinition(id: string): ToothDefinition | undefined {
  if (TEETH_BY_ID[id]) return TEETH_BY_ID[id];
  const stripped = id.replace('tooth_', '');
  return TEETH_BY_ID[stripped];
}

