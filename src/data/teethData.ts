export interface ToothGeometricProfile {
  crownHeight: number; // Vertical clinical crown length (occlusocervical / incisocervical)
  mesiodistalWidth: number; // Mesiodistal width in scene units
  labiolingualDepth: number; // Labiolingual / buccolingual thickness
  cervicalTaper: number; // Constriction ratio at CEJ (cementoenamel junction)
  cuspCount: number; // 0 for incisor chisel, 1 for canine, 2 for premolar, 4-5 for molar
  morphology: 'incisor' | 'canine' | 'premolar' | 'molar';
  cingulumProminence: number; // Lingual cingulum prominence (0 to 1)
  fossaDepth: number; // Lingual / occlusal concavity depth (0 to 1)
  cervicalOffset: number; // Calibrated insertion depth into the gingival cuff (prevents floating & excessive mesh overlap)
  labialTorque: number; // Labial (+) / lingual (-) crown inclination in radians
  mesiodistalTip: number; // Mesial (+) / distal (-) crown angulation in radians
}

